(function(){
  const grid=document.querySelector("[data-project-grid]");
  const buttons=[...document.querySelectorAll("[data-project-filter]")];
  const subWrap=document.querySelector("[data-maquinado-subfilters]");
  const subButtons=[...document.querySelectorAll("[data-project-subfilter]")];
  let category="todos", subcategory="todos";

  function card(p){
    const badge=p.demo?'<span class="project-demo-badge">PLANTILLA DEMO</span>':'<span class="project-real-badge">PROYECTO REYGUE</span>';
    const visual=p.image
      ? `<button class="project-image-button" type="button" data-lightbox="${p.image}" data-lightbox-alt="${p.alt||p.title}" aria-label="Ampliar imagen: ${p.title}"><img src="${p.image}" alt="${p.alt||p.title}" loading="lazy"></button>`
      : `<div class="project-placeholder" aria-hidden="true"><span>RG</span><small>ESPACIO PARA FOTO REAL</small></div>`;
    const sub=p.subcategoryLabel?`<span class="project-subcategory">${p.subcategoryLabel}</span>`:"";
    return `<article class="project-card reveal" data-category="${p.category}">
      <div class="project-media">${visual}${badge}</div>
      <div class="project-body"><span class="eyebrow">${p.categoryLabel}</span>${sub}<h3>${p.title}</h3><p>${p.summary}</p>
      <div class="project-processes">${p.processes.map(x=>`<span>${x}</span>`).join("")}</div>
      <a class="text-link transition-link" href="proyecto.html?id=${encodeURIComponent(p.id)}">Ver detalle <span>→</span></a></div></article>`;
  }

  function list(){
    return window.REYGUE_PROJECTS.filter(p=>{
      if(category!=="todos"&&p.category!==category)return false;
      if(category==="maquinado"&&subcategory!=="todos"&&!(p.subcategories||[]).includes(subcategory))return false;
      return true;
    });
  }
  function render(){
    if(!grid)return;
    grid.innerHTML=list().map(card).join("");
    if(subWrap)subWrap.hidden=category!=="maquinado";
    document.dispatchEvent(new CustomEvent("reygue:content-updated"));
  }
  buttons.forEach(b=>b.addEventListener("click",()=>{
    category=b.dataset.projectFilter; subcategory="todos";
    buttons.forEach(x=>x.classList.toggle("is-active",x===b));
    subButtons.forEach(x=>x.classList.toggle("is-active",x.dataset.projectSubfilter==="todos"));
    render();
  }));
  subButtons.forEach(b=>b.addEventListener("click",()=>{
    category="maquinado"; subcategory=b.dataset.projectSubfilter;
    buttons.forEach(x=>x.classList.toggle("is-active",x.dataset.projectFilter==="maquinado"));
    subButtons.forEach(x=>x.classList.toggle("is-active",x===b));
    render();
  }));
  render();

  const detail=document.querySelector("[data-project-detail]");
  if(detail){
    const id=new URLSearchParams(location.search).get("id");
    const p=window.REYGUE_PROJECTS.find(x=>x.id===id)||window.REYGUE_PROJECTS[0];
    document.title=`${p.title} | Grupo REYGUE Industrial`;
    if(!p.demo){
      detail.innerHTML=`
        <div class="detail-project-head"><div><span class="eyebrow">${p.categoryLabel}</span><span class="project-real-inline">PROYECTO REYGUE</span>
          <h1>${p.title}</h1><p class="lead">${p.summary}</p></div>
          <a class="btn btn-ghost transition-link" href="proyectos.html">← Volver a proyectos</a></div>
        <div class="project-detail-layout">
          <button class="project-detail-visual reveal" type="button" data-lightbox="${p.image}" data-lightbox-alt="${p.alt||p.title}" aria-label="Ampliar imagen: ${p.title}">
            <img src="${p.image}" alt="${p.alt||p.title}">
          </button>
          <div class="project-spec-grid">
            <article class="project-spec reveal"><span>Tipo de componente</span><strong>${p.componentType}</strong></article>
            <article class="project-spec reveal"><span>Procesos relacionados</span><div class="project-processes">${p.processes.map(x=>`<span>${x}</span>`).join("")}</div></article>
            <article class="project-spec reveal"><span>Aplicaciones</span><ul>${p.applications.map(x=>`<li>${x}</li>`).join("")}</ul></article>
            <article class="project-spec reveal"><span>Fabricación / revisión a partir de</span><ul>${p.referenceModes.map(x=>`<li>${x}</li>`).join("")}</ul></article>
          </div>
        </div>
        <div class="project-detail-note"><strong>Nota técnica:</strong> ${p.technicalNote}</div>
        <div class="project-detail-note"><strong>Trabajo real REYGUE:</strong> la fotografía corresponde a un proyecto realizado por Grupo REYGUE Industrial. No se publican datos de cliente, dimensiones o tolerancias que no hayan sido proporcionados.</div>
        <div class="project-detail-actions"><a class="btn btn-primary transition-link" href="contacto.html#cotizar">Cotizar una pieza similar</a><button class="btn btn-ghost" type="button" data-whatsapp data-message="Hola, quiero consultar la fabricación o reparación de una pieza similar a ${p.title}. Tengo un plano, muestra o fotografías para compartir.">Consultar por WhatsApp</button></div>`;
    } else {
      detail.innerHTML=`<div class="detail-project-head"><div><span class="eyebrow">${p.categoryLabel}</span><span class="inline-demo">PLANTILLA DEMO — NO ES UN PROYECTO REAL</span>
        <h1>${p.title}</h1><p class="lead">${p.summary}</p></div>
        <a class="btn btn-ghost transition-link" href="proyectos.html">← Volver a proyectos</a></div>
        <div class="project-story-grid">
        ${[["01","Necesidad",p.need],["02","Solución",p.solution],["03","Diseño",p.design],["04","Fabricación",p.manufacturing],["05","Resultado",p.result]]
        .map(i=>`<article class="story-step reveal"><span class="story-number">${i[0]}</span><div><h2>${i[1]}</h2><p>${i[2]}</p></div></article>`).join("")}
        </div><div class="project-detail-note"><strong>Plantilla:</strong> reemplaza este contenido cuando agregues un proyecto real de esta categoría.</div>`;
    }
    document.dispatchEvent(new CustomEvent("reygue:content-updated"));
  }
})();
